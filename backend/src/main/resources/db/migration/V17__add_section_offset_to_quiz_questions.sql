-- 퀴즈 문항이 가리키는 개념 설명 구간의 시작 시각을 담는다.
--
-- FRD §19.4 는 "학생은 풀이 직후 정답과 해당 개념의 녹화 구간을 확인할 수 있다" 를 요구하고,
-- 학생 화면의 해설 카드에도 "관련 강의 구간 24:10 다시 보기" 링크가 있다. 그런데 문항에는
-- 그 시각을 담을 자리가 없어 링크를 만들 수 없었다.
--
-- NULL 을 허용한다. 모델이 범위 밖 구간 번호를 답하면 그 문항의 구간만 비우고 문항은 살린다 —
-- 복습 추천은 항목을 버리면 되지만(0~5개) 문항을 버리면 3~5개 불변식이 깨진다. 비어 있으면
-- 다시 보기 링크만 뜨지 않는다.
--
-- 구간 외래키가 아니라 시각을 담는 이유는 review_recommendations 와 같다. 링크가 필요한 것은
-- 재생 위치이고, 개념 구간 행이 나중에 다시 계산돼도 이미 만든 퀴즈의 링크는 그때 가리킨
-- 지점에 그대로 있어야 한다.

ALTER TABLE `quiz_questions`
    ADD COLUMN `section_started_offset_ms` BIGINT NULL
    COMMENT '문항이 가리키는 개념 설명 구간의 시작 시각(ms). 근거 구간을 특정하지 못했으면 NULL'
    AFTER `explanation`;
