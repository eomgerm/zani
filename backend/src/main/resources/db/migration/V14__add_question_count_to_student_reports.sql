-- 학생이 수업 중 남긴 질문 수. 리포트의 "한눈에 보기" 박스가 쓴다.
--
-- 서버가 chat_messages 를 세지 않고 모델이 판단한 값을 저장한다. 공개 채팅에는 질문만 있지 않다 —
-- "감사합니다", "네", "잘 들려요" 도 같은 테이블에 같은 모양으로 들어온다. 행 수를 세면 그것까지
-- 질문으로 세고, 반대로 물음표만 찾으면 "이 부분 다시 설명해주실 수 있나요" 같은 완곡한 요청과
-- 물음표 없는 질문을 놓친다. 무엇이 질문인지는 문장을 읽어야 알 수 있다.
--
-- 저장하는 이유는 판정 근거가 남지 않기 때문이다. 같은 채팅을 나중에 다시 세면 모델이 다르게
-- 판단할 수 있고, 그러면 학생이 어제 본 숫자와 오늘 본 숫자가 달라진다. 리포트는 그 시점의
-- 분석 결과이므로 값을 그때 굳힌다.
--
-- 기존 행은 NULL 이다. 249 가 아직 어디서도 실행되지 않아 대상은 시연 시드가 넣은 행뿐이고,
-- 시드도 같은 변경에서 값을 채웠다. NOT NULL 로 조이지 않는 이유는 이 값이 모델 응답에 의존해
-- 이후 스키마 변경 없이도 비어 있는 리포트가 생길 수 있어야 하기 때문이다.

ALTER TABLE `student_reports`
    ADD COLUMN `question_count` INT NULL
    COMMENT '학생이 수업 중 남긴 질문 수. AI 가 공개 채팅에서 질문인 발화만 세어 판단한다'
    AFTER `participation_summary`;
